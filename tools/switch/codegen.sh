#!/usr/bin/env bash
# Codegen for the native (deko3d) Switch build: rexglue v0.10.0, the base of rexglue-sdk-nx, then the ARM fixes
# from the Gears of War 2 PC port (tools/switch/codegen/, BSD-3-Clause).
#
#   tools/switch/codegen.sh
#
# Output: out/codegen-nx/generated/default/ (the PC build's generated/ is not touched).
# Needs the v0.10.0 host rexglue built by tools/setup.sh (thirdparty/rexglue-sdk), or REXGLUE=<path to rexglue>.
#   BARRIERS=0  skip the memory-barrier pass (to compare)
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
out="$root/out/codegen-nx"
gen="$out/generated/default"
sdk="${SINGULARITY_SDK_NX:-$root/thirdparty/rexglue-sdk-nx}"
rexglue="${REXGLUE:-$(find "$root/thirdparty/rexglue-sdk/out" -name rexglue -type f -perm -u+x 2>/dev/null | head -1)}"
[ -x "$rexglue" ] || { echo "No v0.10.0 rexglue (set REXGLUE)" >&2; exit 1; }
[ -f "$root/singularity-extract/default.xex" ] || { echo "No singularity-extract/default.xex" >&2; exit 1; }

mkdir -p "$out"
# The same project as the PC build, with the output in out/codegen-nx/.
cat > "$out/singularity_manifest.toml" <<EOF
# Generated by tools/switch/codegen.sh for the native Switch build.
[project]
name = "singularity"
sdk_version = "0.10.0"
game_root = "../../singularity-extract"

[entrypoint]
file_path = "../../singularity-extract/default.xex"
out_directory_path = "generated/default"
includes = ["../../overrides.toml"]
EOF

echo "== codegen ($("$rexglue" --version 2>/dev/null | head -1 || echo rexglue))"
(cd "$out" && "$rexglue" codegen singularity_manifest.toml) > "$out/codegen.log" 2>&1 || {
  echo "codegen failed, see $out/codegen.log" >&2; exit 1; }
tail -2 "$out/codegen.log"

fixes="$root/tools/switch/codegen"
echo "== unresolved branches and jump tables"
(cd "$out" && python3 "$fixes/patch_switch_traps.py" "generated/default/*.cpp") | tail -2
if [ "${BARRIERS:-1}" = 1 ]; then
  echo "== memory barriers"
  (cd "$out" && python3 "$fixes/patch_memory_barriers.py" generated/default/*.cpp) | tail -2
fi
echo "== spin hints"
# Its default only accepts the PC port's Android copy (out/android); ours is out/codegen-nx (as gears2-nx calls it).
python3 - "$fixes" "$out" "$gen"/*.cpp <<'PY' | tail -2
import sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
import patch_spin_hints
sys.exit(patch_spin_hints.main(sys.argv[3:], allowed_root=Path(sys.argv[2]).resolve()))
PY
echo "== Singularity game patches"
(cd "$out" && python3 "$fixes/patch_singularity.py" "generated/default/*.cpp")
echo "== 540p scene (game patch 3, from gears2-nx 1.1.0)"
(cd "$out" && python3 "$fixes/patch_scene_resolution.py" "generated/default/*.cpp")

# gears2-nx's CPU passes (GPL-3.0, tools/switch/codegen/patch_*.py), after the game patches as there. They rely on
# switch/tools/make_nx_pch.py's macros (REX_FUNC_PROLOGUE_LEAF, REX_SLOAD/SSTORE, the inline DEFINE_REX_FUNC).
srcs=("$root/switch/src" "$sdk/src" "$sdk/include")
echo "== leaf functions without the stack guard"
(cd "$out" && python3 "$fixes/patch_leaf_prologue.py" generated/default/*.cpp) | tail -1
echo "== guest stack accesses without volatile"
(cd "$out" && python3 "$fixes/patch_stack_access.py" generated/default/*.cpp) | tail -1
echo "== inlinable calls"
(cd "$out" && python3 "$fixes/patch_inline_calls.py" "${srcs[@]}" -- generated/default/singularity_recomp.*.cpp) | tail -1 | cut -c1-200
if [ "${LOCALREGS:-1}" = 1 ]; then
  echo "== guest registers in host locals"
  (cd "$out" && PLR_MAP="$out/patch_local_regs.check.map" python3 "$fixes/patch_local_regs.py" \
    generated/default/singularity_inline_helpers.h "${srcs[@]}" -- generated/default/singularity_recomp.*.cpp) \
    > "$out/patch_local_regs.log" 2>&1 || { tail -20 "$out/patch_local_regs.log"; exit 1; }
  tail -1 "$out/patch_local_regs.log" | cut -c1-200
fi
echo "done: $gen"
